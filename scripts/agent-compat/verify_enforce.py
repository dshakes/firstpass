#!/usr/bin/env python3
"""Assertions + doc generation for scripts/agent-compat/run_enforce.sh.

Reads the run's SQLite trace store, the fake upstream's request log, and the CLI outputs; checks
every claim below; prints a PASS/FAIL table; writes the generated "Enforce mode" section into the
compat doc between markers; exits non-zero on any failure.

The store is read through sqlite3 only (read-only URI). The hash chain is verified by the repo's own
`firstpass verify --json`, not re-implemented here.
"""

import argparse
import json
import os
import sqlite3
import subprocess
import sys
import time

BEGIN = "<!-- enforce-mode:begin (generated by scripts/agent-compat/run_enforce.sh; do not hand-edit) -->"
END = "<!-- enforce-mode:end -->"
SESSION_PREFIXES = ("conv:", "meta:", "agent:")


def load_traces(db):
    try:
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
        try:
            rows = con.execute(
                "SELECT seq, session, body FROM traces ORDER BY seq"
            ).fetchall()
        finally:
            con.close()
    except sqlite3.Error:
        return []
    return [dict(json.loads(b), _seq=s, _session_col=sess) for s, sess, b in rows]


def read(path, default=""):
    try:
        with open(path) as f:
            return f.read()
    except OSError:
        return default


def provider_of(t):
    return t["attempts"][0]["provider"] if t.get("attempts") else ""


def gate_summary(a):
    return ",".join(f"{g['gate_id']}={g['verdict']}" for g in a.get("gates", []))


def chain(attempts):
    return "; ".join(
        f"{a['model']}[{gate_summary(a)}]->{a['verdict']}" for a in attempts
    )


def escalated(t):
    a = t["attempts"]
    return bool(
        len(a) >= 2
        and a[0]["verdict"] == "fail"
        and a[1]["verdict"] == "pass"
        and any(g["verdict"] == "fail" for g in a[0]["gates"])
        and a[1]["gates"]
        and all(g["verdict"] == "pass" for g in a[1]["gates"])
        and a[1]["rung"] == a[0]["rung"] + 1
        and t["final"]["served_rung"] == a[1]["rung"]
    )


def evaluate(args, have):
    """Run every check once. Returns (checks, facts); checks = [(name, ok, detail)]."""
    checks, facts = [], {}
    traces = load_traces(args.db)
    reqs = json.loads(read(args.requests, "[]") or "[]")
    facts["receipts"] = len(traces)
    facts["upstream_requests"] = [
        {
            "model": r.get("body_shape", {}).get("model") or "?",
            "scripted": r["scripted"],
        }
        for r in reqs
        if r.get("scripted")
    ]
    up = facts["upstream_requests"]

    def add(name, ok, detail=""):
        checks.append((name, bool(ok), detail))

    add("receipts written in the trace store", traces, f"{len(traces)} receipts")
    add(
        "every receipt has mode enforce",
        traces and all(t["mode"] == "enforce" for t in traces),
        ",".join(sorted({t["mode"] for t in traces})),
    )

    # Hash chain, via the repo's own verifier (an empty store reads as valid, so also require >0).
    p = subprocess.run(
        [args.bin, "verify", "--json"],
        capture_output=True,
        text=True,
        env=dict(os.environ, FIRSTPASS_DB=args.db),
    )
    try:
        rep = json.loads(p.stdout)
    except ValueError:
        rep = {}
    add(
        "hash chain verifies (firstpass verify)",
        p.returncode == 0
        and rep.get("valid") is True
        and rep.get("receipts") == len(traces) > 0,
        f"exit={p.returncode} receipts={rep.get('receipts')} valid={rep.get('valid')}",
    )

    if "claude" in have:
        for n in (1, 2):
            rc = read(f"{args.work}/claude-{n}.rc").strip()
            try:
                doc = json.loads(read(f"{args.work}/claude-{n}.out"))
            except ValueError:
                doc = {}
            add(
                f"claude -p run {n} completes its turn",
                rc == "0" and doc.get("is_error") is False and bool(doc.get("result")),
                f"exit={rc} is_error={doc.get('is_error')} result={str(doc.get('result'))[:50]!r}",
            )
        ct = [t for t in traces if provider_of(t) == "anthropic"]
        esc = [t for t in ct if escalated(t)]
        add(
            "claude: escalation receipt (cheap rung fails gate, top rung passes)",
            esc,
            chain(esc[0]["attempts"])
            if esc
            else f"{len(ct)} anthropic receipts, none escalated",
        )
        if esc:
            a0, a1 = esc[0]["attempts"][:2]
            add(
                "claude: ladder models are haiku then sonnet",
                "haiku" in a0["model"] and "sonnet" in a1["model"],
                f"{a0['model']} -> {a1['model']}",
            )
            add(
                "claude: failing gate was tool-args-valid",
                any(
                    g["gate_id"].startswith("tool-args-valid")
                    and g["verdict"] == "fail"
                    for g in a0["gates"]
                ),
                gate_summary(a0),
            )
        cheap_ok = [
            t
            for t in ct
            if len(t["attempts"]) == 1
            and t["final"]["served_rung"] == 0
            and "haiku" in t["attempts"][0]["model"]
            and t["attempts"][0]["verdict"] == "pass"
        ]
        add(
            "claude: cheap rung serves a turn that passes its gates",
            cheap_ok,
            f"{len(cheap_ok)} receipts",
        )
        scripted = [u["scripted"] for u in up if "claude" in u["model"]]
        add(
            "claude: upstream saw cheap-bad-tool-args then top-valid-tool",
            "cheap-bad-tool-args" in scripted and "top-valid-tool" in scripted,
            ",".join(scripted),
        )
        add(
            "claude: agent loop ran a tool and sent a tool_result back",
            "text-after-tool-result" in scripted,
            "tool_result request reached upstream",
        )
        sess = {}
        for t in ct:
            sess.setdefault(t["session_id"], []).append(t)
        grouped = {
            s: v
            for s, v in sess.items()
            if s.startswith(SESSION_PREFIXES) and len(v) >= 2
        }
        add(
            "claude: turns of one run share a derived session id",
            grouped,
            "; ".join(f"{s} x{len(v)}" for s, v in grouped.items())
            or f"sessions={list(sess)}",
        )
        facts["claude_sessions"] = {s: len(v) for s, v in sess.items()}

    if "aider" in have:
        rc = read(f"{args.work}/aider.rc").strip()
        out = read(f"{args.work}/aider.out")
        add(
            "aider --message completes its turn",
            rc == "0" and "Scripted reply" in out,
            f"exit={rc} reply_seen={'Scripted reply' in out}",
        )
        ot = [t for t in traces if provider_of(t) == "openai"]
        esc = [t for t in ot if escalated(t)]
        add(
            "aider: escalation receipt (empty cheap reply fails non-empty, top passes)",
            esc,
            chain(esc[0]["attempts"])
            if esc
            else f"{len(ot)} openai receipts, none escalated",
        )
        if esc:
            a0, a1 = esc[0]["attempts"][:2]
            add(
                "aider: ladder models are gpt-4.1-mini then gpt-5.5",
                "4.1-mini" in a0["model"] and "5.5" in a1["model"],
                f"{a0['model']} -> {a1['model']}",
            )
    return checks, facts


def render(have, checks, facts, doctor, rc):
    skipped = [
        f"- **{n}**: skipped, `{n}` not on PATH."
        for n in ("claude", "aider")
        if n not in have
    ]
    healthy = "not healthy" not in doctor.lower() and "healthy" in doctor.lower()
    lines = [
        BEGIN,
        "",
        "## Enforce mode",
        "",
        "Generated by `scripts/agent-compat/run_enforce.sh`. Real CLIs, `$0`, localhost only: every provider "
        "base URL points at a scriptable fake upstream (`fake_upstream.py`, `FAKE_SCRIPT=enforce`); keys are dummies.",
        "",
        '**Config** (written into the run\'s work dir and named by `FIRSTPASS_CONFIG`): the `agent = "claude-code"` '
        "route is `anthropic/claude-haiku-4-5 -> anthropic/claude-sonnet-5`; the catch-all route is "
        '`openai/gpt-4.1-mini -> openai/gpt-5.5`. Both are `mode = "enforce"` with gates `non-empty` and '
        "`tool-args-valid`, `max_rungs_per_request = 2`, and "
        '`session_promotion = { after_failures = 3, window = "30m" }`. All four models are priced in the built-in table.',
        "",
        "**Script** (per model, deterministic): the cheap model's first reply is bad (a `tool_use` whose args "
        "violate the declared schema when tools are declared, an empty reply otherwise); later cheap replies and "
        "every top-model reply are valid; a request ending in a `tool_result` gets plain text.",
        "",
        f"**Result: {'PASS' if rc == 0 else 'FAIL'}** (harness exit code {rc}). Receipts in the store: "
        f"{facts.get('receipts', 0)}. `firstpass doctor` on this config: {'healthy' if healthy else 'NOT healthy'}.",
        "",
        "| Check | Result | Detail |",
        "|---|---|---|",
    ]
    for name, ok, detail in checks:
        lines.append(
            f"| {name} | {'PASS' if ok else '**FAIL**'} | {detail.replace('|', '/')} |"
        )
    lines += [
        "",
        "Upstream requests that hit a scripted model, in order (model the rung called : scripted behaviour):",
        "",
    ]
    lines += [
        f"1. `{u['model']}` : `{u['scripted']}`"
        for u in facts.get("upstream_requests", [])
    ]
    lines += [
        "",
        "**Not exercised**",
        "",
        "- Real model quality: the fake upstream returns canned text. This proves routing, gating, escalation, "
        "session grouping and receipts, not answer quality.",
        "- Gates beyond `non-empty` and `tool-args-valid` (schema, tests and judge each need their own `[[gate]]`).",
        "- Upstream streaming: enforce buffers the upstream reply to gate it, then serves the CLI's `stream: true` from it.",
        "- gemini, cline, cursor-agent, codex: see the compatibility matrix above.",
    ]
    return "\n".join(lines + skipped + ["", END, ""])


def splice(doc, section):
    text = read(doc)
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        text = head.rstrip("\n") + "\n\n" + section + tail.lstrip("\n")
    else:
        text = text.rstrip("\n") + "\n\n" + section
    with open(doc, "w") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser()
    for k in (
        "work",
        "db",
        "requests",
        "bin",
        "have",
        "doctor-file",
        "top-fails",
        "upstream-port",
    ):
        ap.add_argument("--" + k, required=True)
    ap.add_argument("--doc")
    ap.add_argument("--timeout", type=float, default=8.0)
    args = ap.parse_args()
    have = args.have.split()
    doctor = read(args.doctor_file)

    # The trace writer is async: re-evaluate until every check holds or the deadline passes.
    deadline = time.time() + args.timeout
    while True:
        checks, facts = evaluate(args, have)
        if (checks and all(ok for _, ok, _ in checks)) or time.time() > deadline:
            break
        time.sleep(0.5)
    if not have:
        checks.append(
            ("at least one CLI available", False, "neither claude nor aider on PATH")
        )
    rc = 0 if all(ok for _, ok, _ in checks) else 1
    print("\n=== Enforce-mode results ===")
    for name, ok, detail in checks:
        print(f"  {'PASS' if ok else 'FAIL'}  {name}  [{detail}]")
    for n in ("claude", "aider"):
        if n not in have:
            print(f"  SKIP  {n} (not on PATH)")
    print(
        f"  receipts={facts.get('receipts')}  claude sessions={facts.get('claude_sessions')}"
    )
    if args.top_fails == "1":
        print(
            "  (FAKE_TOP_FAILS=1 negative control: a failing exit is the expected outcome)"
        )
    elif args.doc:
        splice(args.doc, render(have, checks, facts, doctor, rc))
        print(f"  doc section written: {args.doc}")
    sys.exit(rc)


if __name__ == "__main__":
    main()
